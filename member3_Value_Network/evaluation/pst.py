TABLES = {
    chess.PAWN: PAWN,
    chess.KNIGHT: KNIGHT,
    chess.BISHOP: BISHOP,
    chess.ROOK: ROOK,
    chess.QUEEN: QUEEN,
}


def pst_score(board: chess.Board) -> float:
    """Điểm vị trí quân (Trắng - Đen), đơn vị Tốt."""
    phase = game_phase(board)
    total = 0.0
    for square, piece in board.piece_map().items():
        white = piece.color == chess.WHITE
        idx = square ^ 56 if white else square
        if piece.piece_type == chess.KING:
            value = phase * KING_MIDDLEGAME[idx] + (1.0 - phase) * KING_ENDGAME[idx]
        else:
            value = TABLES[piece.piece_type][idx]
        total += value if white else -value
    return total / 100.0
